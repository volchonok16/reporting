// Builds packages/editor/src/help/diagram-reference.ts — the reference of
// every kind of diagram (DocPlan's «Справочник», with its coloured examples)
// as plain data for the help window, in Russian and in English. The engine's
// help and syntax colouring are plain string functions, run here outside a
// browser. English: packages/diagrams/vendor/reference-en.json maps each piece
// of Russian prose to its translation; examples (<pre>, <code>) stay as they
// are — the engine reads its commands in Russian.
// Usage: node tools/diagrams-help.mjs (after changing packages/diagrams/vendor/).
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import vm from 'node:vm';
import { ROOT } from './transform.mjs';

const VENDOR = join(ROOT, 'packages/diagrams/vendor');
const files = (await readdir(VENDOR)).sort();
const pick = (part) => files.find((f) => f.includes(part));
const context = vm.createContext({ console });
context.window = context;
for (const f of [pick('00-layouts'), pick('syntax-highlight'), pick('79-help')]) {
  vm.runInContext(await readFile(join(VENDOR, f), 'utf8'), context, { filename: f });
}
const english = JSON.parse(await readFile(join(VENDOR, 'reference-en.json'), 'utf8'));
const missing = new Set();
const CYRILLIC = /[А-Яа-яЁё]/;

/** The Russian prose of a reference replaced by English, examples kept. */
function translate(html) {
  const kept = [];
  const keep = (s) => `\u0001${kept.push(s) - 1}\u0001`;
  let out = html.replace(/<pre>[\s\S]*?<\/pre>/g, keep).replace(/<code>[\s\S]*?<\/code>/g, (s) => `\u0002${kept.push(s) - 1}\u0002`);
  out = out.replace(/>([^<>]+)</g, (whole, run) => {
    const key = run.trim().replace(/\u0002\d+\u0002/g, '⟨c⟩');
    if (!CYRILLIC.test(key.replace(/⟨c⟩/g, ''))) return whole;
    const en = english[key];
    if (!en) {
      missing.add(key);
      return whole;
    }
    const codes = run.match(/\u0002\d+\u0002/g) ?? [];
    let i = 0;
    const text = en.replace(/⟨c⟩/g, () => codes[i++] ?? '');
    const lead = /^\s*/.exec(run)[0];
    const trail = /\s*$/.exec(run)[0];
    return `>${lead}${text}${trail}<`;
  });
  return out.replace(/[\u0001\u0002](\d+)[\u0001\u0002]/g, (_, n) => kept[Number(n)]);
}

const layouts = vm.runInContext('VALID_DIAGRAM_LAYOUTS', context);
const out = layouts.map((layout) => {
  const { title, html } = vm.runInContext(`simDiagramHelp(${JSON.stringify(layout)})`, context);
  // As written: the indents inside <pre> are part of the syntax.
  const ru = html.trim();
  if (!english[title]) missing.add(title);
  return { layout, title, html: ru, titleEn: english[title] ?? title, htmlEn: translate(ru) };
});
const ts = `// Generated by tools/diagrams-help.mjs from DocPlan's reference (packages/diagrams/vendor/) — do not edit here.
// The commands of each kind of diagram, with coloured examples (HTML of our own, shown in the help window),
// in Russian and in English (the examples stay Russian: the engine reads its commands so).

export interface DiagramReference {
  layout: string;
  title: string;
  html: string;
  titleEn: string;
  htmlEn: string;
}

export const DIAGRAM_REFERENCE: DiagramReference[] = ${JSON.stringify(out, null, 2)};
`;
await writeFile(join(ROOT, 'packages/editor/src/help/diagram-reference.ts'), ts);
console.log(`Справочник схем: ${out.length} типов → packages/editor/src/help/diagram-reference.ts`);
if (missing.size) console.log(`Без перевода (${missing.size}):\n${[...missing].join('\n')}`);
