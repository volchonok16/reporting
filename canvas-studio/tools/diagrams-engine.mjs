// Builds packages/diagrams/engine.js — the diagram engine taken from DocPlan
// (parsers, layouts and SVG renderers of 23 kinds of diagrams) — from the
// files in packages/diagrams/vendor/, in their order, as one classic script
// (they are written as browser scripts sharing globals; a module would change
// their meaning). The editor loads it only when a diagram is opened.
// Usage: node tools/diagrams-engine.mjs
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { ROOT } from './transform.mjs';

const VENDOR = join(ROOT, 'packages/diagrams/vendor');
const OUT = join(ROOT, 'packages/diagrams/engine.js');

const files = (await readdir(VENDOR)).filter((f) => f.endsWith('.js')).sort();
const parts = ['// Generated by tools/diagrams-engine.mjs from packages/diagrams/vendor/ — do not edit here.\n'];
for (const f of files) parts.push(`\n// ===== ${f} =====\n${await readFile(join(VENDOR, f), 'utf8')}\n;\n`);
await writeFile(OUT, parts.join(''));
console.log(`Движок схем: ${files.length} файлов → packages/diagrams/engine.js`);
